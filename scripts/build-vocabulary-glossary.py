#!/usr/bin/env python3
"""Generate the site's vocabulary glossary from the shared Anki vocabulary catalog."""
import argparse
from collections import defaultdict
import html
import json
from pathlib import Path
import re
from audio_tables import button

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs/vocabulary-glossary.md'


def render():
    catalog = json.loads((ROOT / 'data/vocabulary/moag.json').read_text())
    groups = {}
    for entry in catalog['entries']:
        identity = (entry['malayalam'], entry['english'])
        group = groups.setdefault(identity, dict(chapters=set(), audio=[], origins=set()))
        group['chapters'].add(entry['chapter'])
        group['origins'].add(entry['origin'])
        group['audio'].extend(entry['audio'])
    letters = defaultdict(list)
    for (word, meaning), group in groups.items():
        initial = re.search(r'[\u0d05-\u0d14\u0d15-\u0d3a\u0d7a-\u0d7f]', word)
        letters[initial[0] if initial else 'Other'].append((word, meaning, group))
    def escape(s):
        return html.escape(s).replace('|', '&#124;')
    lines = ['<!-- Generated by scripts/build-vocabulary-glossary.py; edit lesson tables and rebuild the vocabulary catalog. -->',
             '# Vocabulary Glossary', '',
             f"Browse {len(groups)} word-and-meaning entries from all 25 lessons, including the additional recorded forms used in the Anki decks. Repeated entries are combined; different meanings remain separate.", '',
             'This generated vocabulary index complements the [original textbook glossary](glossary.md). Lesson links open the vocabulary tables. A dash in the Audio column means no recording is available.', '',
             '<div class="vocabulary-glossary-controls">',
             '<label for="vocabulary-query">Search Malayalam or English</label>',
             '<input id="vocabulary-query" type="search" placeholder="Word or meaning…" autocomplete="off">',
             '<label for="vocabulary-chapter">Lesson</label>',
             '<select id="vocabulary-chapter"><option value="">All lessons</option>'+''.join(f'<option value="{n}">Lesson {n:02}</option>' for n in range(1,26))+'</select>',
             f'<p id="vocabulary-count" role="status" aria-live="polite">{len(groups)} entries</p>', '</div>', '',
             '<div class="lesson-audio"><p><strong>Selected vocabulary recording</strong></p><audio data-table-audio-player controls preload="none" aria-label="Select a glossary recording"></audio></div>', '',
             'Jump to a letter: '+ ' · '.join(f'[{letter}](#vocabulary-letter-{ord(letter[0]):x})' for letter in sorted(letters)), '']
    for letter in sorted(letters):
        lines += [f'<a id="vocabulary-letter-{ord(letter[0]):x}"></a>', f'## {letter}', '', '| Malayalam | English | Lessons | Audio |', '|---|---|---|---|']
        for word, meaning, group in sorted(letters[letter], key=lambda x:(x[0],x[1])):
            links = ' · '.join(f'[{n}](lesson{n}.md#lesson{n}-vocabulary)' for n in sorted(group['chapters']))
            controls = ' '.join(button(dict(clip, status='matched'), word) for clip in group['audio']) or '—'
            lines.append(f'| {escape(word)} | {escape(meaning)} | {links} | {controls} |')
        lines.append('')
    return '\n'.join(lines)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args=parser.parse_args()
    text=render()
    if args.check:
        assert OUT.read_text()==text, 'Vocabulary glossary needs rebuilding'
    else:
        OUT.write_text(text)
    print(f"{'Checked' if args.check else 'Built'} {OUT.relative_to(ROOT)}")


if __name__=='__main__':
    main()
